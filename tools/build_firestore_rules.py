"""Builds firestore.rules from js/catalog.js, so every order is checked against the real prices.

Usage: python tools/build_firestore_rules.py
Then publish firestore.rules (Firebase console > Firestore Database > Rules, or `firebase deploy --only firestore:rules`).
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_LINES = 15  # different items per order; js/backend.js uses the same limit

src = open(os.path.join(ROOT, "js", "catalog.js"), encoding="utf-8").read()
catalog = json.loads(src[src.index("{"): src.rindex("}") + 1])

prices = ",\n".join(
    "        '{}': {{{}}}".format(slug, ", ".join(f"'{size}': {price}" for size, price in p["prices"].items()))
    for slug, p in catalog.items()
)
item_checks = "\n        && ".join(f"lineOk(items, {i}, cat)" for i in range(MAX_LINES))
line_sum = "\n        + ".join(f"lineTotal(items, {i})" for i in range(MAX_LINES))

RULES = f"""rules_version = '2';

// Generated by tools/build_firestore_rules.py from js/catalog.js. Edit those, not this file.
service cloud.firestore {{
  match /databases/{{database}}/documents {{

    // ---------- Shared checks ----------

    function verified() {{
      return request.auth != null && request.auth.token.email_verified == true;
    }}

    // No backslashes: the rules language would read them literally. [.] is a plain dot.
    function isEmail(value) {{
      return value is string && value.size() <= 254
        && value.matches('^[^@ ]+@[^@ ]+[.][^@ ]{{2,}}$');
    }}

    function textOk(value, min, max) {{
      return value is string && value.size() >= min && value.size() <= max;
    }}

    // ---------- Orders: prices must match the catalogue ----------

    function catalog() {{
      return {{
{prices}
      }};
    }}

    function itemOk(item, cat) {{
      return item is map
        && item.keys().hasOnly(['slug', 'name', 'size', 'qty', 'price'])
        && item.keys().hasAll(['slug', 'name', 'size', 'qty', 'price'])
        && item.slug is string && item.slug in cat
        && item.size is string && item.size in cat[item.slug]
        && item.price == cat[item.slug][item.size]
        && item.qty is int && item.qty >= 1 && item.qty <= 10
        && textOk(item.name, 1, 60);
    }}

    function lineOk(items, i, cat) {{
      return items.size() <= i || itemOk(items[i], cat);
    }}

    function lineTotal(items, i) {{
      return items.size() > i ? items[i].price * items[i].qty : 0;
    }}

    function orderOk(o) {{
      let items = o.items;
      let cat = catalog();
      return o.keys().hasOnly(['uid', 'email', 'name', 'number', 'items', 'subtotal', 'createdAt'])
        && o.uid == request.auth.uid
        && o.email == request.auth.token.email
        && textOk(o.name, 1, 80)
        && textOk(o.number, 4, 24)
        && o.createdAt == request.time
        && items is list && items.size() >= 1 && items.size() <= {MAX_LINES}
        && {item_checks}
        && o.subtotal == {line_sum};
    }}

    match /orders/{{orderId}} {{
      allow create: if verified() && orderOk(request.resource.data);
      allow read: if request.auth != null && resource.data.uid == request.auth.uid;
      allow update, delete: if false;
    }}

    // ---------- Contact form: write-only, read in the Firebase console ----------

    match /messages/{{messageId}} {{
      allow create: if request.resource.data.keys().hasOnly(['name', 'email', 'topic', 'message', 'createdAt', 'uid'])
        && textOk(request.resource.data.name, 1, 80)
        && isEmail(request.resource.data.email)
        && request.resource.data.topic in ['Order', 'Product advice', 'Gifting', 'Other']
        && textOk(request.resource.data.message, 10, 4000)
        && request.resource.data.createdAt == request.time
        && (!('uid' in request.resource.data) || (request.auth != null && request.resource.data.uid == request.auth.uid));
      allow read, update, delete: if false;
    }}

    // ---------- Newsletter: one document per address, write-only ----------

    // Signing up twice just refreshes the date, so a repeat sign-up never shows an error.
    match /subscribers/{{email}} {{
      allow create, update: if request.resource.data.keys().hasOnly(['email', 'createdAt'])
        && request.resource.data.email == email
        && email == email.lower()
        && isEmail(email)
        && request.resource.data.createdAt == request.time;
      allow read, update, delete: if false;
    }}

    // Everything else is closed.
  }}
}}
"""

with open(os.path.join(ROOT, "firestore.rules"), "w", encoding="utf-8", newline="\n") as f:
    f.write(RULES)
print(f"firestore.rules written: {len(catalog)} products, up to {MAX_LINES} lines per order")
